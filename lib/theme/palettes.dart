/// The four DayDeck colour schemes. `modern` is the default; `light` is the
/// accessibility fallback. Schemes are intentionally just colour tokens — no
/// other design decisions leak in.
enum DayDeckScheme {
  modern, classicGreen, amber, light, amoled,
  draculaDark, draculaLight, nordDark, nordLight,
  solarizedDark, solarizedLight, gruvboxDark, gruvboxLight,
  monokaiDark, monokaiLight, catppuccinMocha, catppuccinLatte,
  tokyoNight, tokyoDay, oneDark, oneLight, rosePine, rosePineDawn,
  everforestDark, everforestLight, amberDark, amberLight,
  matrixDark, matrixLight, hackerDark, hackerLight,
  synthwaveDark, synthwaveLight, signalDark, signalLight,
}

class TerminalPalette {
  const TerminalPalette({
    required this.scheme,
    required this.label,
    required this.descriptor,
    required this.bg,
    required this.panel,
    required this.panel2,
    required this.border,
    required this.text,
    required this.dim,
    required this.accent,
    required this.accent2,
    required this.good,
    required this.warn,
    required this.bad,
    required this.brightness,
    required this.scanlineAlpha,
  });

  final DayDeckScheme scheme;
  final String label;
  final String descriptor;

  // Surfaces
  final Color bg;
  final Color panel;
  final Color panel2;
  final Color border;

  // Content
  final Color text;
  final Color dim;
  final Color accent;
  final Color accent2;
  final Color good;
  final Color warn;
  final Color bad;

  final Brightness brightness;

  /// Opacity of the subtle CRT scanline texture painted over the UI.
  final double scanlineAlpha;

  bool get isLight => brightness == Brightness.light;
}

